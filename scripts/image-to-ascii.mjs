#!/usr/bin/env node
/**
 * Image → ASCII portrait generator.
 *
 *   node scripts/image-to-ascii.mjs <input-image> [--width 68] [--charset ".:;!*=*#$@"]
 *
 * Writes `src/data/ascii-portrait.ts` with one string per rendered row. The
 * hero renders those rows in a monospace grid, so keep the width under ~80
 * columns to stay legible on a laptop.
 *
 * The default charset runs light → dark. Bright pixels (near-white studio
 * backgrounds) are dropped entirely so the portrait floats on the paper.
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const args = process.argv.slice(2);
const input = args[0];
const flag = (name, fallback) => {
  const i = args.indexOf(`--${name}`);
  return i === -1 ? fallback : args[i + 1];
};

if (!input) {
  console.error(
    "Usage: node scripts/image-to-ascii.mjs <image> [--width 68] [--charset \".:;!*=*#$@\"]"
  );
  process.exit(1);
}

const WIDTH = Number(flag("width", 68));
const CHARSET = flag("charset", ".:;!*=*#$@");
const WHITE_CUTOFF = Number(flag("white-cutoff", 232));
// Monospace glyphs are roughly twice as tall as they are wide.
const CELL_ASPECT = 0.46;

const { data, info } = await sharp(input)
  .flatten({ background: "#ffffff" })
  .grayscale()
  .resize({ width: WIDTH })
  .raw()
  .toBuffer({ resolveWithObject: true });

const height = Math.round(info.height * CELL_ASPECT);
const rows = [];

for (let y = 0; y < height; y++) {
  let row = "";
  for (let x = 0; x < info.width; x++) {
    const px = data[y * info.width + x];

    if (px >= WHITE_CUTOFF) {
      row += " ";
      continue;
    }

    // Boost contrast a little: the avatar is a mid-grey marble statue and
    // reads as a flat block without it.
    const normalized = Math.min(1, Math.max(0, (px - 24) / 190));
    const index = Math.min(
      CHARSET.length - 1,
      Math.floor((1 - normalized) * CHARSET.length)
    );
    row += CHARSET[index];
  }
  rows.push(row.replace(/\s+$/, ""));
}

const out = `// Generated by scripts/image-to-ascii.mjs — edit the source image, not this file.
// Source: ${path.basename(input)}
export const ASCII_PORTRAIT_WIDTH = ${info.width};

export const ASCII_PORTRAIT: string[] = ${JSON.stringify(rows, null, 2)};
`;

const target = path.join(process.cwd(), "src/data/ascii-portrait.ts");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);

console.log(`Wrote ${rows.length}×${info.width} ASCII portrait to ${target}`);
